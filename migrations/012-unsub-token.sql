-- 退訂連結的 token（每一封訂閱信都會帶著它）。
--
-- 為什麼要有這個欄位：2026-09-09 helen 的密碼重設信被寄信商擋掉，根因在
-- 2026-09-20 才查清楚——**她是在 Gmail 裡按了「取消訂閱」**，寄信商收到之後
-- 把她加進**帳號層級**的退訂名單，於是連她自己索取的密碼重設信一起擋掉。
--
-- 她會去按那顆按鈕，是因為**我們的信裡沒有自己的退訂連結**：唯一的開關在
-- 「我的帳號」頁裡，而信的結尾只寫著「可在系統內設定」卻沒給路。
-- 同〈「我的帳號」分頁〉那條「沒有人找得到的功能等於不存在」。
--
-- **這裡存明碼，與 ics_feed 只存雜湊不同**，而那不是偷懶：兩者的需求相反。
-- ICS 的 token 交給使用者之後伺服器再也不需要它，所以存雜湊；退訂連結是
-- **我們自己每寄一封信就要放一次**，雜湊回推不出來。
--
-- 明碼的代價講清楚：資料庫外洩時，拿到它的人能做的事只有一件——把某個人的
-- 通知關掉。它登不了入、讀不到任何排程，也**打不開**任何開關（要再打開一律
-- 回系統裡按）。而同一份外洩早就包含那個人的整份排程，所以這不是最弱的一環。
--
-- 可以是 NULL：既有的列不必回填，第一次要寄信時才產生（見 ensureUnsubToken）。
ALTER TABLE reminder_feed ADD COLUMN unsub_token TEXT;
